// Pure-Kotlin bot engine: builds and tests anywhere with a JDK.
include(":core")

// The Android XR app needs the Android SDK. It is only included when an SDK
// is configured (ANDROID_HOME or sdk.dir in local.properties), so CI and
// non-Android machines can still build and test :core.
val localProps = file("local.properties")
val hasAndroidSdk = System.getenv("ANDROID_HOME") != null ||
    System.getenv("ANDROID_SDK_ROOT") != null ||
    (localProps.exists() && localProps.readText().contains("sdk.dir"))
if (hasAndroidSdk) include(":android")
